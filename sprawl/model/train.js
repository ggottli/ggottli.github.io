// Trains the Sprawl shape model: multinomial logistic regression over hashed text features.
// Run: node model/train.js   → writes ../sprawl-model.js (weights as base64 int8) and prints held-out accuracy.
'use strict';
const fs=require('fs'), path=require('path');
const F=require('../sprawl-features.js');
const {generate}=require('./data.js');
const TYPES=['note','todo','heading','link','question','quote','event','reminder','timer','habit','goal','color','calc','convert','split','expense','countdown','timezone','random','poll','contact'];
const C=TYPES.length, B=F.BUCKETS;

let seed=42; const rnd=()=>{ seed=(seed*1664525+1013904223)>>>0; return seed/4294967296; };
function shuffle(a){ for(let i=a.length-1;i>0;i--){ const j=Math.floor(rnd()*(i+1)); [a[i],a[j]]=[a[j],a[i]]; } return a; }

const data=shuffle(generate()).map(d=>({x:F.featurize(d.text), y:TYPES.indexOf(d.type), text:d.text}));
const evalSet=JSON.parse(fs.readFileSync(path.join(__dirname,'eval.json'),'utf8')).map(([text,type])=>({x:F.featurize(text), y:TYPES.indexOf(type), text}));
console.log(`train ${data.length} examples, eval ${evalSet.length}`);

const W=new Float32Array(B*C), bias=new Float32Array(C), G=new Float32Array(B*C), Gb=new Float32Array(C);
function logits(x){ const out=new Float32Array(C); const s=1/Math.sqrt(x.length||1); for(let c=0;c<C;c++) out[c]=bias[c]; for(const i of x){ const o=i*C; for(let c=0;c<C;c++) out[c]+=W[o+c]*s; } return out; }
function softmax(z){ const m=Math.max(...z); let sum=0; const p=z.map(v=>{ const e=Math.exp(v-m); sum+=e; return e; }); return p.map(v=>v/sum); }
const LR=.35, L2=1e-5, EPOCHS=14;
for(let ep=0;ep<EPOCHS;ep++){
  shuffle(data); let loss=0;
  for(const d of data){
    const s=1/Math.sqrt(d.x.length||1), p=softmax(logits(d.x)); loss-=Math.log(p[d.y]+1e-9);
    for(let c=0;c<C;c++){ const g=(p[c]-(c===d.y?1:0)); Gb[c]+=g*g; bias[c]-=LR*g/Math.sqrt(Gb[c]+1e-8);
      for(const i of d.x){ const k=i*C+c, gi=g*s+L2*W[k]; G[k]+=gi*gi; W[k]-=LR*gi/Math.sqrt(G[k]+1e-8); } }
  }
  const acc=a=>a.filter(d=>{ const z=logits(d.x); let b=0; for(let c=1;c<C;c++) if(z[c]>z[b]) b=c; return b===d.y; }).length/a.length;
  console.log(`epoch ${ep+1} loss ${(loss/data.length).toFixed(3)} train ${(acc(data)*100).toFixed(1)}% eval ${(acc(evalSet)*100).toFixed(1)}%`);
}
// report eval mistakes
let wrong=0; for(const d of evalSet){ const z=logits(d.x); let b=0; for(let c=1;c<C;c++) if(z[c]>z[b]) b=c; if(b!==d.y){ wrong++; console.log(`  miss: ${JSON.stringify(d.text)} → ${TYPES[b]} (want ${TYPES[d.y]})`); } }
console.log(`eval accuracy ${((1-wrong/evalSet.length)*100).toFixed(1)}%`);

// quantize to int8 and emit
let mx=0; for(const v of W) mx=Math.max(mx,Math.abs(v)); const scale=mx/127;
const q=Buffer.alloc(B*C); for(let i=0;i<W.length;i++) q[i]=Math.round(W[i]/scale)&255;
const out=`// Generated by model/train.js — do not edit. Multinomial logistic regression over hashed features (see sprawl-features.js).
window.SPRAWL_MODEL=${JSON.stringify({types:TYPES, buckets:B, scale:+scale.toPrecision(6), bias:[...bias].map(v=>+v.toFixed(4)), w:q.toString('base64')})};
`;
fs.writeFileSync(path.join(__dirname,'..','sprawl-model.js'),out);
console.log(`wrote sprawl-model.js (${(out.length/1024).toFixed(0)} KB)`);
